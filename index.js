app.post("/webhook", async (req, res) => {
  const message = req.body.message;

  if (!message || !message.text) {
    return res.sendStatus(200);
  }

  const chatId = message.chat.id;
  const userText = message.text;
  const mode = detectMode(userText);

  if (!userSessions[chatId]) {
    userSessions[chatId] = [];
  }

  userSessions[chatId].push({
    role: "user",
    content: userText
  });

  if (userSessions[chatId].length > 10) {
    userSessions[chatId] = userSessions[chatId].slice(-10);
  }

  try {
    const aiResponse = await axios.post(
      "https://api.openai.com/v1/chat/completions",
      {
        model: "gpt-4o-mini",
        messages: [
          {
            role: "system",
            content: `
MODE: ${mode}

${PROMPTS[mode] || PROMPTS.NAVIGATOR}
`
          },
          ...userSessions[chatId]
        ]
      },
      {
        headers: {
          Authorization: `Bearer ${OPENAI_API_KEY}`,
          "Content-Type": "application/json"
        }
      }
    );

    const reply = aiResponse.data.choices[0].message.content;

    userSessions[chatId].push({
      role: "assistant",
      content: reply
    });

    if (userSessions[chatId].length > 10) {
      userSessions[chatId] = userSessions[chatId].slice(-10);
    }

    await axios.post(
      `https://api.telegram.org/bot${TELEGRAM_TOKEN}/sendMessage`,
      {
        chat_id: chatId,
        text: reply
      }
    );
  } catch (error) {
    console.error("OpenAI error:", error.response?.data || error.message || error);

    userSessions[chatId].pop();

    await axios.post(
      `https://api.telegram.org/bot${TELEGRAM_TOKEN}/sendMessage`,
      {
        chat_id: chatId,
        text: "Произошла ошибка, попробуй ещё раз."
      }
    );
  }

  res.sendStatus(200);
});

